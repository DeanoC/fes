package emitc

import (
	"fmt"
	"strings"
	"unicode"

	"github.com/DeanoC/mister-packages/internal/pack"
)

// GenerateFabric emits standalone C macros for unsigned 32-bit fabric constants.
// It requires no system headers and declares no device or runtime admission.
func GenerateFabric(fabric *pack.FabricFile) (string, error) {
	if err := fabric.Validate(); err != nil {
		return "", err
	}
	return generate(fabric.ID, fabric.Major, "fabric", fabric.Constants)
}

// GenerateABI emits the declared numeric constants, without expanding ABI
// identity or interface metadata. In particular ABITag and AbiTag must not
// generate the same C macro twice. This supplies no activation permission.
func GenerateABI(abi *pack.ABIFile) (string, error) {
	if err := abi.Validate(); err != nil {
		return "", err
	}
	return generate(abi.ID, abi.Major, "abi", abi.Constants)
}

func generate(id string, major uint16, directory string, constants []pack.ABIConstant) (string, error) {
	fileName := strings.NewReplacer(".", "_", "-", "_").Replace(id)
	guard := fmt.Sprintf("%s_CONSTANTS_V%d_H", strings.ToUpper(fileName), major)
	seen := map[string]bool{guard: true}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by mister-packages from packages/%s/%s.yaml. Do not edit.\n", directory, fileName)
	fmt.Fprintf(&b, "#ifndef %s\n#define %s\n\n", guard, guard)
	for _, constant := range constants {
		name := constantName(constant.Name)
		if seen[name] {
			return "", fmt.Errorf("%s %q generates duplicate C macro %q", directory, id, name)
		}
		seen[name] = true
		fmt.Fprintf(&b, "#define %s 0x%08xU\n", name, uint64(constant.Value))
	}
	fmt.Fprintf(&b, "\n#endif /* %s */\n", guard)
	return b.String(), nil
}

// constantName follows the existing fabric Verilog macro naming rule.
func constantName(name string) string {
	var b strings.Builder
	for i, r := range name {
		if i > 0 && unicode.IsUpper(r) {
			previous := rune(name[i-1])
			if unicode.IsLower(previous) || unicode.IsDigit(previous) {
				b.WriteByte('_')
			}
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}
