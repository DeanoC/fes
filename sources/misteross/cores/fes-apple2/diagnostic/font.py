ORDER = "@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_ !\"#$%&'()*+,-./0123456789:;<=>?"


def glyph_rows(char: str) -> list[int]:
    rows = []
    for text in _GLYPHS[char]:
        assert len(text) == 5, char
        value = 0
        for column, dot in enumerate(text):
            if dot == "#":
                value |= 1 << (column + 1)
        rows.append(value)
    rows.append(0)
    return rows


def table() -> bytes:
    assert len(ORDER) == 64 and len(set(ORDER)) == 64
    data = bytearray()
    for char in ORDER:
        data.extend(glyph_rows(char))
    return bytes(data)


def screen_code(char: str, mode: str = "normal") -> int:
    """Apple II screen byte for an ASCII character (upper case only)."""
    code = ord(char.upper())
    assert 0x20 <= code <= 0x5F, char
    if mode == "normal":
        return code | 0x80
    return {"inverse": 0x00, "flash": 0x40}[mode] | (code & 0x3F)


def _packed(name: str, words: list[int], width: int) -> list[str]:
    bits = len(words) * width
    value = 0
    for index, word in enumerate(words):
        value |= word << (index * width)
    digits = f"{value:0{bits // 4}x}"
    chunks = [digits[offset:offset + 64] for offset in range(0, len(digits), 64)]
    lines = [f"localparam [{bits - 1}:0] {name} = {{"]
    for index, chunk in enumerate(chunks):
        lines.append(f"    {len(chunk) * 4}'h{chunk}" + ("," if index + 1 < len(chunks) else ""))
    return lines + ["};"]


def verilog() -> str:
    data = list(table())
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by cores/fes-apple2/diagnostic/font.py; do not edit.",
        "// Open FES Apple II character generator, entry {glyph[5:0], row[2:0]},",
        "// dot 0 in bit 0. APPLE2_FONT packs eight bits per entry for simulation;",
        "// APPLE2_FONT_INIT is the same table as the INIT of a 1024x10 M10K.",
    ]
    lines += _packed("APPLE2_FONT", data, 8)
    lines += _packed("APPLE2_FONT_INIT", data + [0] * (1024 - len(data)), 10)
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verilog", type=Path, required=True)
    args = parser.parse_args()
    args.verilog.write_text(verilog())


if __name__ == "__main__":
    main()
