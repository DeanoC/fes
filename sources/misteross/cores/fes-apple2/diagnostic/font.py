"""Original open 5x7 character generator for the FES Apple II video.

The Apple II+ displays 64 glyphs selected by bits 5..0 of a screen byte:
@ A-Z [ \\ ] ^ _ in 00-1F and space ! " # ... ? in 20-3F. Bits 7..6 select
inverse, flashing or normal rendering in hardware, so only 64 glyphs exist.
These glyphs were drawn for FES and are not a copy of Apple's character ROM.

Each glyph is eight rows of seven dots. Bit 0 is the leftmost dot. The five
drawn columns occupy dots 1..5; row 7 is blank. ``--hex`` writes the 512-byte
table consumed by ``cores/fes-apple2/rtl/apple2_charrom.v``.
"""

