ORDER = "@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_ !\"#$%&'()*+,-./0123456789:;<=>?"


def glyph_rows(char: str) -> list[int]:
    rows = []
    for text in _GLYPHS[char]:
        assert len(text) == 5, char
        value = 0
        for column, dot in enumerate(text):
            if dot == "#":
                value |= 1 << (column + 1)
        rows.append(value)
    rows.append(0)
    return rows


def table() -> bytes:
    assert len(ORDER) == 64 and len(set(ORDER)) == 64
    data = bytearray()
    for char in ORDER:
        data.extend(glyph_rows(char))
    return bytes(data)


def screen_code(char: str, mode: str = "normal") -> int:
    """Apple II screen byte for an ASCII character (upper case only)."""
    code = ord(char.upper())
    assert 0x20 <= code <= 0x5F, char
    if mode == "normal":
        return code | 0x80
    return {"inverse": 0x00, "flash": 0x40}[mode] | (code & 0x3F)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--hex", type=Path, required=True)
    args = parser.parse_args()
    args.hex.write_text("".join(f"{value:02x}\n" for value in table()))


if __name__ == "__main__":
    main()
