"""Writes hid_set2_reference.h, keyboard_tb's expected set 2 bytes for every
fes.keyboard.hid usage, from a Linux source tree's tables rather than from
pc386_hid_keyboard's own table (Microsoft's USB HID to PS/2 translation).

A usage's code is Linux's hid_keyboard[] key looked up in the inverse of
atkbd_set2_keycode[], whose index is the set 2 code with its E0 prefix in
bit 7 and its own bit 7 in bit 8 (atkbd_compat_scancode). Where Linux has no
single standard code the reference takes Microsoft's:

  F7 (40h)          83, not Linux's alternative 02
  Print Screen      E0 12 E0 7C, break E0 F0 7C E0 F0 12
  Pause             E1 14 77 E1 F0 14 F0 77, no break
  F13-F24 (68h-73h) 08 10 18 20 28 30 38 40 48 50 57 5F; Linux's atkbd
                    gives some of them other codes and the rest none
  Stop (78h)        none; Linux maps it to E0 28

usage: hid_set2_reference.py LINUX_SOURCE_TREE
"""
from __future__ import annotations

from pathlib import Path
import re
import sys

OUTPUT = Path(__file__).with_name('hid_set2_reference.h')
USAGES = (*range(0x00, 0x80), *range(0xe0, 0xe8))
F13_F24 = (0x08, 0x10, 0x18, 0x20, 0x28, 0x30, 0x38, 0x40, 0x48, 0x50, 0x57, 0x5f)


def table(path: Path, name: str) -> list[int]:
    text = path.read_text()
    body = text[text.index(name):]
    body = body[body.index('{') + 1:body.index('};')]
    body = re.sub(r'#ifdef.*?#else', '', body, flags=re.S).replace('#endif', '')
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [0 if value.strip() == 'unk' else int(value) for value in body.split(',') if value.strip()]


def sequences(linux: Path) -> dict[int, tuple[list[int], list[int]]]:
    hid = table(linux / 'drivers/hid/hid-input.c', 'hid_keyboard[256]')
    set2 = table(linux / 'drivers/input/keyboard/atkbd.c', 'atkbd_set2_keycode[ATKBD_KEYMAP_SIZE]')
    if len(hid) != 256 or len(set2) != 256 + 5:  # atkbd lists 100h-104h past the E0 half
        raise SystemExit(f'unexpected table sizes {len(hid)} {len(set2)}')
    inverse: dict[int, list[int]] = {}
    for index, key in enumerate(set2):
        if key:
            inverse.setdefault(key, []).append(index)
    result = {}
    for usage in USAGES:
        candidates = inverse.get(hid[usage], []) if hid[usage] else []
        if usage == 0x40:
            candidates = [0x103]
        if usage == 0x46:
            result[usage] = ([0xe0, 0x12, 0xe0, 0x7c], [0xe0, 0xf0, 0x7c, 0xe0, 0xf0, 0x12])
            continue
        if usage == 0x48:
            result[usage] = ([0xe1, 0x14, 0x77, 0xe1, 0xf0, 0x14, 0xf0, 0x77], [])
            continue
        if 0x68 <= usage <= 0x73:
            code = F13_F24[usage - 0x68]
            result[usage] = ([code], [0xf0, code])
            continue
        if usage == 0x78 or not candidates:
            continue
        if len(candidates) != 1:
            raise SystemExit(f'usage {usage:02x}: Linux gives several set 2 codes {candidates}')
        index = candidates[0]
        code = (index & 0x7f) | ((index & 0x100) >> 1)
        if index & 0x80:
            result[usage] = ([0xe0, code], [0xe0, 0xf0, code])
        else:
            result[usage] = ([code], [0xf0, code])
    return result


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    linux = Path(sys.argv[1])
    rows = []
    for usage, (make, release) in sequences(linux).items():
        bytes_ = lambda values: '{' + ', '.join(f'0x{value:02x}' for value in values) + '}'
        rows.append(f'    {{0x{usage:02x}, {len(make)}, {bytes_(make)}, {len(release)}, {bytes_(release)}}},')
    OUTPUT.write_text('\n'.join([
        '// SPDX-License-Identifier: MIT',
        '// Generated by hid_set2_reference.py from a Linux 6.12 tree\'s hid-input.c and',
        '// atkbd.c tables, with the exceptions its docstring lists. Do not edit.',
        '#pragma once',
        '#include <cstdint>',
        '',
        'struct Set2Reference {',
        '    uint8_t usage;  // 00h-7Fh, or a modifier E0h-E7h',
        '    uint8_t make_length, make[8], break_length, release[8];',
        '};',
        '',
        'static const Set2Reference SET2_REFERENCE[] = {',
        *rows,
        '};',
        '',
    ]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
