"""Open 8x8 screen-code font for the FES Commodore 64 pathfinder.

Screen codes follow the C64 layout: A–Z are 1–26, space is 32, digits are
48–57. Bit 7 is the leftmost pixel. The generated function is what both the
VIC text scanner and a CHAREN=0 read of $D000 use. It is not the Commodore
character ROM.
"""

from __future__ import annotations

import argparse
from pathlib import Path

# code -> eight row bytes. Unlisted codes read as zero.
GLYPHS: dict[int, tuple[int, ...]] = {
    0x00: (0x3C, 0x66, 0x6E, 0x6E, 0x60, 0x62, 0x3C, 0x00),  # @
    0x20: (0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
}


def _glyph(rows: str) -> tuple[int, ...]:
    return tuple(int(row, 2) for row in rows.strip().split())


