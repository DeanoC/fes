"""Open 8x8 screen-code font for the FES Commodore 64 pathfinder.

Screen codes follow the C64 layout: @ is 0, A-Z are 1-26, space is 32, digits
are 48-57. Bit 7 is the leftmost pixel and ``#`` is ink. The glyphs are the
square-cornered FES block face drawn for FES (the RAM tester uses the same
face); they are not copied from the Commodore character ROM. The generated
bytes form the open diagnostic character ROM used by simulation.
"""

