for index, glyph in enumerate(_LETTERS.values(), start=1):
    GLYPHS[index] = _glyph(glyph)
for index, glyph in enumerate(_DIGITS.values(), start=48):
    GLYPHS[index] = _glyph(glyph)


def image() -> bytes:
    """Two 2 KiB open pages, with inverse glyphs in each page's upper half."""
    page=bytearray()
    for code in range(256):
        glyph=GLYPHS.get(code&127,(0,)*8)
        page.extend(byte^255 if code&128 else byte for byte in glyph)
    return bytes(page+page)
