// Simulation only: actual standard core and DE25 endpoints, internal 16K ROM
// diagnostic, and read-only machine/RAM observations. Expansion qualification
// and the physical memory/clock/transmitter boundaries remain separate.
module fes_de25_standard_session_harness (
    input wire clk_sys, pixel_clk, reset_n, pixel_reset_n,
    input wire display_ready, clock_fault, expansion_running,
    input wire [4:0] computer_address,
    input wire computer_read, computer_write,
    input wire [3:0] computer_byteenable,
    input wire [31:0] computer_writedata,
    output wire [31:0] computer_readdata,
    output wire computer_readdatavalid, computer_writeresponsevalid, computer_waitrequest,
    output wire [1:0] computer_response,
    input wire [6:0] address,
    input wire read, write,
    input wire [3:0] byteenable,
    input wire [31:0] writedata,
    output wire [31:0] readdata,
    output wire readdatavalid, writeresponsevalid, waitrequest,
    output wire [1:0] response,
    output wire [31:0] avm_address,
    output wire [4:0] avm_burstcount,
    output wire avm_read,
    output wire [15:0] avm_byteenable,
    input wire avm_waitrequest,
    input wire [127:0] avm_readdata,
    input wire avm_readdatavalid,
    input wire [1:0] avm_response,
    output wire [27:0] video,
    output wire signed [15:0] audio_sample,
    output wire exec_reset,
    output wire [15:0] bus_addr,
    output wire [7:0] bus_wdata,
    output wire bus_mreq_n, bus_iorq_n, bus_rd_n, bus_wr_n, bus_m1_n, bus_rfsh_n,
    output wire bus_cpu_clock,
    input wire [7:0] bus_rdata, bus_peek_data,
    input wire bus_dsel, bus_romcs, bus_wait, bus_ram_present,
    input wire [15:0] peek_addr,
    output wire [7:0] peek_data,
    output wire [15:0] cpu_addr,
    output wire ram_write_enable,
    output wire ui_active, faulted, quiesced_sys ,
    input wire request,
    input wire [6:0] opcode,
    input wire [7:0] index,
    input wire [15:0] argument,
    input wire [27:0] machine,
    output wire locked,
    output wire [27:0] observed_machine,
    output reg [31:0] cpu_writes = 0
);
    fes_de25_zx81_standard #(.BUILD_ID(128'h00112233445566778899aabbccddeeff),
        .EXPANSION_SOCKET(0), .FIRMWARE_INIT("standard-session-rom.hex")) board (
        .clk_sys(clk_sys),
        .pixel_clk(pixel_clk),
        .reset_n(reset_n),
        .pixel_reset_n(pixel_reset_n),
        .video_ready(display_ready),
        .clock_fault(clock_fault),
        .expansion_running(expansion_running),
        .computer_address(computer_address),
        .computer_read(computer_read),
        .computer_write(computer_write),
        .computer_byteenable(computer_byteenable),
        .computer_writedata(computer_writedata),
        .computer_readdata(computer_readdata),
        .computer_readdatavalid(computer_readdatavalid),
        .computer_writeresponsevalid(computer_writeresponsevalid),
        .computer_waitrequest(computer_waitrequest),
        .computer_response(computer_response),
        .scanout_address(address),
        .scanout_read(read),
        .scanout_write(write),
        .scanout_byteenable(byteenable),
        .scanout_writedata(writedata),
        .scanout_readdata(readdata),
        .scanout_readdatavalid(readdatavalid),
        .scanout_writeresponsevalid(writeresponsevalid),
        .scanout_waitrequest(waitrequest),
        .scanout_response(response),
        .avm_address(avm_address),
        .avm_burstcount(avm_burstcount),
        .avm_read(avm_read),
        .avm_byteenable(avm_byteenable),
        .avm_waitrequest(avm_waitrequest),
        .avm_readdata(avm_readdata),
        .avm_readdatavalid(avm_readdatavalid),
        .avm_response(avm_response),
        .video(video),
        .video_rgb(), .video_de(), .video_hs(), .video_vs(),
        .audio_sample(audio_sample),
        .exec_reset(exec_reset),
        .bus_addr(bus_addr),
        .bus_wdata(bus_wdata),
        .bus_mreq_n(bus_mreq_n),
        .bus_iorq_n(bus_iorq_n),
        .bus_rd_n(bus_rd_n),
        .bus_wr_n(bus_wr_n),
        .bus_m1_n(bus_m1_n),
        .bus_rfsh_n(bus_rfsh_n),
        .bus_cpu_clock(bus_cpu_clock),
        .bus_rdata(bus_rdata),
        .bus_peek_data(bus_peek_data),
        .bus_dsel(bus_dsel),
        .bus_romcs(bus_romcs),
        .bus_wait(bus_wait),
        .bus_ram_present(bus_ram_present),
        .peek_addr(peek_addr),
        .peek_data(peek_data),
        .cpu_addr(cpu_addr),
        .ram_write_enable(ram_write_enable),
        .ui_active(ui_active),
        .display_faulted(faulted),
        .display_quiesced(quiesced_sys)
    );
    assign observed_machine = board.machine_video;
    assign locked = board.display.locked;
    always @(posedge clk_sys)
        if (ram_write_enable && !exec_reset) cpu_writes <= cpu_writes + 1;
endmodule
