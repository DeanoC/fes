"""DE25 derivations of the unchanged DE10 PC/XT sources.

The SDRAM controller's forwarded clock and the computer transport take the
Atari ST's derivations (../atari-st/derive.py). This adds the PC/XT's own:
the 8088 control ROM's generated byte lanes and facts, exactly as the DE10
build writes them, and the framebuffer RAM without its Cyclone V cell.
"""
import hashlib


def sha(data):
    return hashlib.sha256(data).hexdigest()


def control_rom(source):
    """The MCL86 control ROM's four byte lanes and its facts header.

    scripts/sim_fes_pcxt.py's cpu_roms writes the same bytes for the DE10
    builds and simulations: mcl86_ucode.sv reads each lane by name, and
    mcl86_eu_core.sv includes the facts.
    """
    words = [int(word, 16) for word in source.decode().split()]
    if len(words) != 4096 or any(word < 0 or word > 0xffffffff for word in words):
        raise ValueError("MCL86 microcode must contain exactly 4096 32-bit words")
    files = {f"mcl86_ucode_byte{lane}.mem": "".join(f"{(word >> (8 * lane)) & 255:02x}\n" for word in words).encode()
             for lane in range(4)}
    add_masks = [0, 0]
    jump7 = False
    for word in words:
        kind = (word >> 28) & 7
        if kind == 2:
            for index, shift in enumerate((20, 16)):
                add_masks[index] |= 1 << ((word >> shift) & 15)
        jump7 |= kind == 1 and ((word >> 20) & 7) == 7
    files["mcl86_facts.vh"] = (
        '`line 1 "mcl86_facts.vh" 0\n'
        '// Generated from the verified MCL86 control ROM.\n' +
        ''.join(f"localparam [15:0] FES_MC_ADD_OP{i}_MASK = 16'h{mask:04x};\n"
                for i, mask in enumerate(add_masks)) +
        f"localparam [31:0] FES_MC_RESET_WORD = 32'h{words[0x20]:08x};\n" +
        f"localparam FES_MC_JUMP7_USED = 1'b{int(jump7)};\n").encode()
    return files


# coleco_video_dpram selects a Cyclone V altsyncram under the QUARTUS macro
# the board defines, and its own inferred memory otherwise. Here the inferred
# memory is the one, in M20K: the same two registered ports and the same
# one-clock read on each.
RAM_BEGIN = b"`ifdef QUARTUS\n"
RAM_ELSE = b"`else\n"
RAM_END = b"`endif\n"
RAM_STYLE = (b'    (* ramstyle = "M10K" *) reg [DATAWIDTH-1:0] ram [0:NUMWORDS-1];\n',
             b'    (* ramstyle = "M20K" *) reg [DATAWIDTH-1:0] ram [0:NUMWORDS-1];\n')


def retarget_video_ram(source):
    """Keep coleco_video_dpram's inferred memory; drop its Cyclone V cell."""
    if (source.count(RAM_BEGIN) != 1 or source.count(RAM_ELSE) != 1 or source.count(RAM_END) != 1 or
            source.count(RAM_STYLE[0]) != 1 or source.count(b"altsyncram ") != 1):
        raise ValueError("framebuffer RAM adaptation contract changed")
    begin = source.index(RAM_BEGIN)
    middle = source.index(RAM_ELSE)
    end = source.index(RAM_END)
    removed = source[begin:middle + len(RAM_ELSE)]
    if not begin < middle < end or b'"Cyclone V"' not in removed or b"altsyncram" in source[middle:]:
        raise ValueError("framebuffer RAM adaptation contract changed")
    result = source[:begin] + source[middle + len(RAM_ELSE):end] + source[end + len(RAM_END):]
    result = result.replace(*RAM_STYLE)
    return result, {"source_sha256": sha(source), "derived_sha256": sha(result),
                    "removed_sha256": sha(removed + RAM_END), "ramstyle": "M20K"}


# The DE10 video mailbox crosses between the machine and pixel clocks with two
# toggles, the machine hold level and the published bank. It is sound, but the
# design assistant refuses a synchronizer whose first stage takes its clock's
# synchronous reset, a level that leaves a widely shared register, and a bank
# the pixel clock reads through its adoption select (CDC-50002), as the Atari
# ST's video did. Here, as in that derivation:
#   - each toggle and the hold level cross a two-stage synchronizer that runs
#     free of its clock's synchronous reset; the hold leaves a machine-clock
#     launch register of its own;
#   - the published bank is copied into a pixel-clock register on the edge its
#     toggle leaves the synchronizer, with nothing on the path but that
#     register's enable, and the pixel clock adopts the copy from that stage.
# The coordinated reset holds both clocks for many cycles, so the free-running
# stages settle to the reset toggles before either side runs. An adoption can
# take one pixel clock longer to see a new bank; it still lands on an output
# frame start.
VIDEO_EDITS = (
    (b"    (* async_reg = \"true\" *) reg ack_meta, ack_sync, sent_meta, sent_sync;\n",
     b"    (* async_reg = \"true\" *) reg ack_meta, ack_sync, sent_meta, sent_sync;\n"
     b"    reg hold_launch, sent_held;\n    reg [1:0] published_pixel;\n"
     b"    always @(posedge clk_sys) begin\n"
     b"        ack_meta <= received; ack_sync <= ack_meta; hold_launch <= hold;\n    end\n"),
    (b"            ack_meta <= 0; ack_sync <= 0; source_x <= 0; source_y <= 0;\n",
     b"            source_x <= 0; source_y <= 0;\n"),
    (b"            ack_meta <= received; ack_sync <= ack_meta;\n", b""),
    (b"    wire adopt = output_sof && sent_sync != received;\n"
     b"    wire [1:0] read_bank = adopt ? published_bank : front;\n",
     b"    always @(posedge clk_pixel) begin\n"
     b"        sent_meta <= sent; sent_sync <= sent_meta; sent_held <= sent_sync;\n"
     b"        hold_meta <= hold_launch; hold_sync <= hold_meta;\n"
     b"        if (sent_sync != sent_held) published_pixel <= published_bank;\n    end\n"
     b"    wire adopt = output_sof && sent_held != received;\n"
     b"    wire [1:0] read_bank = adopt ? published_pixel : front;\n"),
    (b"            sent_meta <= 0; sent_sync <= 0; hold_meta <= 0; hold_sync <= 0;\n", b""),
    (b"            sent_meta <= sent; sent_sync <= sent_meta;\n"
     b"            hold_meta <= hold; hold_sync <= hold_meta;\n"
     b"            if (adopt) begin front <= published_bank; front_valid <= 1; received <= sent_sync; end\n",
     b"            if (adopt) begin front <= published_pixel; front_valid <= 1; received <= sent_held; end\n"),
)


def retarget_video(source):
    """pcxt_video's mailbox crossings in the shape the design assistant accepts."""
    result, changes = source, []
    for before, after in VIDEO_EDITS:
        if result.count(before) != 1:
            raise ValueError("PC/XT video crossing adaptation contract changed: " +
                             before.decode().strip().splitlines()[0])
        result = result.replace(before, after)
        changes.append({"before": before.decode(), "after": after.decode()})
    return result, {"source_sha256": sha(source), "derived_sha256": sha(result), "changes": changes}
