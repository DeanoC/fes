"""DE25 derivations of the unchanged DE10 PC/XT sources.

The SDRAM controller's forwarded clock and the computer transport take the
Atari ST's derivations (../atari-st/derive.py). This adds the PC/XT's own:
the 8088 control ROM's generated byte lanes and facts, exactly as the DE10
build writes them, and the framebuffer RAM without its Cyclone V cell.
"""
import hashlib


def sha(data):
    return hashlib.sha256(data).hexdigest()


def control_rom(source):
    """The MCL86 control ROM's four byte lanes and its facts header.

    scripts/sim_fes_pcxt.py's cpu_roms writes the same bytes for the DE10
    builds and simulations: mcl86_ucode.sv reads each lane by name, and
    mcl86_eu_core.sv includes the facts.
    """
    words = [int(word, 16) for word in source.decode().split()]
    if len(words) != 4096 or any(word < 0 or word > 0xffffffff for word in words):
        raise ValueError("MCL86 microcode must contain exactly 4096 32-bit words")
    files = {f"mcl86_ucode_byte{lane}.mem": "".join(f"{(word >> (8 * lane)) & 255:02x}\n" for word in words).encode()
             for lane in range(4)}
    add_masks = [0, 0]
    jump7 = False
    for word in words:
        kind = (word >> 28) & 7
        if kind == 2:
            for index, shift in enumerate((20, 16)):
                add_masks[index] |= 1 << ((word >> shift) & 15)
        jump7 |= kind == 1 and ((word >> 20) & 7) == 7
    files["mcl86_facts.vh"] = (
        '`line 1 "mcl86_facts.vh" 0\n'
        '// Generated from the verified MCL86 control ROM.\n' +
        ''.join(f"localparam [15:0] FES_MC_ADD_OP{i}_MASK = 16'h{mask:04x};\n"
                for i, mask in enumerate(add_masks)) +
        f"localparam [31:0] FES_MC_RESET_WORD = 32'h{words[0x20]:08x};\n" +
        f"localparam FES_MC_JUMP7_USED = 1'b{int(jump7)};\n").encode()
    return files


# coleco_video_dpram selects a Cyclone V altsyncram under the QUARTUS macro
# the board defines, and its own inferred memory otherwise. Here the inferred
# memory is the one, in M20K: the same two registered ports and the same
# one-clock read on each.
RAM_BEGIN = b"`ifdef QUARTUS\n"
RAM_ELSE = b"`else\n"
RAM_END = b"`endif\n"
RAM_STYLE = (b'    (* ramstyle = "M10K" *) reg [DATAWIDTH-1:0] ram [0:NUMWORDS-1];\n',
             b'    (* ramstyle = "M20K" *) reg [DATAWIDTH-1:0] ram [0:NUMWORDS-1];\n')


def retarget_video_ram(source):
    """Keep coleco_video_dpram's inferred memory; drop its Cyclone V cell."""
    if (source.count(RAM_BEGIN) != 1 or source.count(RAM_ELSE) != 1 or source.count(RAM_END) != 1 or
            source.count(RAM_STYLE[0]) != 1 or source.count(b"altsyncram ") != 1):
        raise ValueError("framebuffer RAM adaptation contract changed")
    begin = source.index(RAM_BEGIN)
    middle = source.index(RAM_ELSE)
    end = source.index(RAM_END)
    removed = source[begin:middle + len(RAM_ELSE)]
    if not begin < middle < end or b'"Cyclone V"' not in removed or b"altsyncram" in source[middle:]:
        raise ValueError("framebuffer RAM adaptation contract changed")
    result = source[:begin] + source[middle + len(RAM_ELSE):end] + source[end + len(RAM_END):]
    result = result.replace(*RAM_STYLE)
    return result, {"source_sha256": sha(source), "derived_sha256": sha(result),
                    "removed_sha256": sha(removed + RAM_END), "ramstyle": "M20K"}
