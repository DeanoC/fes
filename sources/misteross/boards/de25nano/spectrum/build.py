def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


board = load(HERE.parent / "machine/board.py", "de25_spectrum_machine_board")


def component_files(sources):
    """The machine's own component files; the board adds the shared shell."""
    derive = board.module(sources, BOARD + "spectrum/derive.py", "spectrum_selected_derive")
    files, derived = {}, {}
    for name in ("fes_de25_spectrum_standard.v", "fes_de25_spectrum_standard_hw.tcl"):
        files[name] = sources[BOARD + "spectrum/" + name]
    for name in SHARED_FILES:
        files[name] = sources[BOARD + "shared-rtl/" + name]
    for name in MACHINE_FILES:
        files[name] = sources[CORE + name]
    for name in Z80_FILES:
        files[name] = sources[COMMON + "rtl/z80/" + name]
    files["zonx_ay.v"] = sources["sources/misteross/cores/fes-zx81/expansions/zonx_ay.v"]
    files["fes_de25_sdram.v"] = sources[BOARD + "ramtest/sdram.v"]
    files["spectrum_machine_de25.sv"], derived["spectrum_machine_de25.sv"] = derive.retarget_machine(
        sources[CORE + "spectrum_machine.sv"])
    for name in derive.RAM_FILES:
        target = name.replace(".v", "_de25.v")
        files[target], derived[target] = derive.retarget_ram(name, sources[CORE + name])
    files["fes_de25_computer_transport.v"], derived["fes_de25_computer_transport.v"] = derive.transport(
        sources[BOARD + "zx81-hps/fes_de25_computer.v"], native=True)
    files["generated/fes_native_de25_computer.vh"] = sources[NATIVE_COMPUTER_HEADER]
    return files, derived


