#!/usr/bin/env python3
"""Generate cores/fes-c64/rtl/c64_sid_svf_tables.vh for the default C64 SID filter.

The state-variable filter runs once per Phi (0.985248 MHz). Its cutoff
coefficient is 2*sin(pi*f0/Phi) and its damping coefficient is 1/Q, both in
Q20 fixed point. f0(FC) follows the MOS6581 cutoff characteristic published
with reSID 0.16 (Dag Lem), linearly interpolated between its control points,
including the step at FC=1024. 1/Q = 1/(0.707 + RES/15) as in that model.
This is a listening approximation, not a transistor-level model; the exact
reSID 1.0 translation remains available behind c64_sid's RESID_FILTER.
"""
import math
from pathlib import Path

PHI_HZ = 985_248
# (FC, f0 Hz) control points, MOS6581, reSID 0.16 f0_points_6581.
POINTS = [
    (0, 220), (128, 230), (256, 250), (384, 300), (512, 420), (640, 780),
    (768, 1600), (832, 2300), (896, 3200), (960, 4300), (992, 5000),
    (1008, 5400), (1016, 5700), (1023, 6000),
    (1024, 4600), (1152, 4800), (1280, 5300), (1408, 6300), (1536, 8600),
    (1664, 10800), (1792, 11700), (1920, 12000), (2047, 12000),
]
Q20 = 1 << 20
FC_STEP = 16  # table index is FC[10:4]


def f0(fc: int) -> float:
    for (a, fa), (b, fb) in zip(POINTS, POINTS[1:]):
        if a <= fc <= b:
            return fa if a == b else fa + (fb - fa) * (fc - a) / (b - a)
    return POINTS[-1][1]


def cutoff_table() -> list[int]:
    return [round(2 * math.sin(math.pi * f0(index * FC_STEP + FC_STEP // 2) / PHI_HZ) * Q20)
            for index in range(2048 // FC_STEP)]


def damping_table() -> list[int]:
    return [round(Q20 / (0.707 + res / 15)) for res in range(16)]


def render() -> str:
    lines = ["// SPDX-License-Identifier: GPL-2.0-or-later",
             "// Generated by scripts/c64_sid_svf_tables.py; do not edit.",
             "// Q20 cutoff coefficient 2*sin(pi*f0/Phi) indexed by FC[10:4] (MOS6581",
             "// characteristic from reSID 0.16, linear between control points), and",
             "// Q20 damping 1/(0.707 + RES/15) indexed by RES.",
             "function automatic [17:0] svf_cutoff_coefficient(input [6:0] index);",
             " case(index)"]
    for index, value in enumerate(cutoff_table()):
        assert 0 < value < (1 << 18)
        lines.append(f"  7'd{index}:svf_cutoff_coefficient=18'd{value};")
    lines += ["  default:svf_cutoff_coefficient=18'd0;", " endcase", "endfunction",
              "function automatic [20:0] svf_damping_coefficient(input [3:0] resonance);",
              " case(resonance)"]
    for res, value in enumerate(damping_table()):
        assert 0 < value < (1 << 21)
        lines.append(f"  4'd{res}:svf_damping_coefficient=21'd{value};")
    lines += ["  default:svf_damping_coefficient=21'd0;", " endcase", "endfunction", ""]
    return "\n".join(lines)


def main() -> None:
    output = Path(__file__).resolve().parents[1] / "cores/fes-c64/rtl/c64_sid_svf_tables.vh"
    output.write_text(render(), encoding="utf-8")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
