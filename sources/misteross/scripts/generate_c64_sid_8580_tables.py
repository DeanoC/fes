"""Extract the VICE 3.10 default MOS8580 filter tables and check interpolation."""
import argparse
from array import array
import hashlib
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

from generate_c64_sid_audio_vectors import CONFIG, SOURCE_HASHES

# An entry per independently indexed source curve, in units of 65536 values.
# The board has three voices and no external input. Each summer has two
# additional feedback inputs. The mixer can add all three filter outputs.
CURVES = {
    "rev": [1],
    "res": [1] * 16,
    "sum": [2, 3, 4, 5],
    "mix": [1, 2, 3, 4, 5, 6],
    "gain": [1] * 16,
}
STEP_BITS = 8
WORDS_PER_BANK = 512
PROBE = r'''#include "filter8580new.h"
#include <cstdio>
#include <cstdlib>

class Tables : public reSID::Filter {
    static void save(const char* name, const unsigned short* data, size_t count) {
        FILE* file = std::fopen(name, "wb");
        if (!file) std::abort();
        for (size_t i = 0; i < count; ++i) {
            if (std::fputc(data[i] & 255, file) == EOF ||
                std::fputc(data[i] >> 8, file) == EOF) std::abort();
        }
        if (std::fclose(file)) std::abort();
    }
public:
    void extract() {
        set_chip_model(reSID::MOS8580);
        adjust_filter_bias(0.);
        const auto& f = model_filter[1];
        std::printf("%d %d %d %d %u\n", n_param, nVgt, f.voice_DC,
                    f.voice_scale_s14, unsigned(f.mixer[0]));
        save("rev", f.opamp_rev, 65536);
        save("res", &f.resonance[0][0], 16 * 65536);
        save("sum", f.summer, reSID::summer_offset<4>::value);
        save("mix", f.mixer + 1, reSID::mixer_offset<7>::value - 1);
        save("gain", &f.gain[0][0], 16 * 65536);
    }
};
int main() { Tables tables; tables.extract(); }
'''


def extract(source, temp):
    files = ("filter8580new.h", "filter8580new.cc", "filter.h", "dac.h", "dac.cc",
             "resid-config.h", "spline.h", "siddefs.h.in")
    for name in files:
        file = source / name
        if hashlib.sha256(file.read_bytes()).hexdigest() != SOURCE_HASHES[name]:
            raise ValueError(f"{file}: expected unchanged VICE 3.10 source")
        shutil.copyfile(file, temp / name)
    config = (temp / "siddefs.h.in").read_text()
    for key, value in dict(CONFIG, NEW_8580_FILTER="1").items():
        config = config.replace(f"@{key}@", value)
    (temp / "siddefs.h").write_text(config)
    (temp / "extract.cc").write_text(PROBE)
    subprocess.run(["c++", "-std=c++17", "-O2", "extract.cc", "filter8580new.cc",
                    "dac.cc", "-o", "extract"], cwd=temp, check=True)
    return list(map(int, subprocess.check_output(["./extract"], cwd=temp, text=True).split()))


def generate(temp, parameters):
    step = 1 << STEP_BITS
    rom = []
    bases = {}
    for family, (name, curves) in enumerate(CURVES.items()):
        raw = array("H")
        raw.frombytes((temp / name).read_bytes())
        if sys.byteorder != "little":
            raw.byteswap()
        if len(raw) != sum(curves) * 65536:
            raise ValueError(f"{name}: incorrect source table length")
        peak_error = pos = 0
        for selector, count in enumerate(curves, start=int(name == "mix")):
            curve = raw[pos:pos + count * 65536]
            pos += len(curve)
            if name == "rev":
                # VICE has an isolated 0 at address 0, followed by 65533.
                # RTL handles address 0 explicitly; interpolate from its right limit.
                if curve[0] != 0 or curve[1] != 65533:
                    raise ValueError("unexpected reverse op-amp boundary")
                curve[0] = 65535
            # Extrapolate the last point by one index without crossing into the next curve.
            knots = list(curve[::step]) + [min(65535, max(0, 2 * curve[-1] - curve[-2]))]
            bases[(family, selector)] = len(rom)
            rom.extend(knots)
            for k, (a, b) in enumerate(zip(knots, knots[1:])):
                for i, reference in enumerate(curve[k * step:(k + 1) * step]):
                    interp = a + (((b - a) * i + step // 2) >> STEP_BITS)
                    peak_error = max(peak_error, abs(reference - interp))
        print(f"{name}: maximum lookup error {peak_error} / 65535")
    lines = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "// Derived from VICE 3.10 reSID filter8580new, by Dag Lem. See c64_sid.COPYING.",
        "// Generated by scripts/generate_c64_sid_8580_tables.py.",
        f"localparam integer SID8580_STEP_BITS = {STEP_BITS};",
        f"localparam integer SID8580_KNOTS = {len(rom)};",
    ]
    for name, value in zip(("N_PARAM", "N_VGT", "VOICE_DC", "VOICE_SCALE", "MIXER_ZERO"), parameters):
        lines.append(f"localparam integer SID8580_{name} = {value};")
    address_bits = (len(rom) - 1).bit_length()
    lines += [f"function automatic [{address_bits - 1}:0] sid8580_base(input [2:0] family, input [3:0] selector);",
              "    case ({family, selector})"]
    for (family, selector), base in bases.items():
        lines.append(f"        7'h{family * 16 + selector:02x}: sid8580_base = {address_bits}'d{base};")
    lines += ["        default: sid8580_base = 0;", "    endcase", "endfunction",
              "function automatic [8191:0] sid8580_bank(input integer bank);", "    case (bank)"]
    for pos in range(0, len(rom), WORDS_PER_BANK):
        data = "".join(f"{word:04x}" for word in reversed(rom[pos:pos + WORDS_PER_BANK]))
        lines.append(f"        {pos // WORDS_PER_BANK}: sid8580_bank = 8192'h{data};")
    lines += ["        default: sid8580_bank = 0;", "    endcase", "endfunction"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vice-source", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] /
                        "cores/fes-c64/rtl/c64_sid_8580_tables.vh")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as directory:
        temp = Path(directory)
        values = extract(args.vice_source / "src/resid", temp)
        contents = generate(temp, values)
    if args.check:
        if args.output.read_text() != contents:
            parser.error(f"{args.output}: generated constants differ")
    else:
        args.output.write_text(contents)


if __name__ == "__main__":
    main()
