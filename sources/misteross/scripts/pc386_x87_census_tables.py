"""The x87 game census's tables, from pc386_census_summary.py's rows.

    python3 scripts/pc386_x87_census_tables.py --out docs/validation/.../tables.md \
        --jsonl docs/validation/.../census.jsonl quake=build/sim/fes-pc386/game-quakes-x87 ...

Writes one JSON row per run and the record's Markdown tables. The rows hold
counts only: no instruction bytes, frames or game data. The verdict column is
pc24_sufficient from the summary, not a reading of the other columns.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pc386_census_summary as summary  # noqa: E402

X_UNKNOWN = ('unknown', 'unknown')

TITLES = {
    'quake': 'Quake timedemo (DOSBench)', 'screamer': 'Screamer (1995)',
    'chrisb': "Chris's 3D Benchmark", 'tv': 'Terminal Velocity (1995)',
    'doom': 'DOOM (1993)', 'wolf3d': 'Wolfenstein 3D (1992)',
    'ultima6': 'Ultima VI: The False Prophet (1990)',
    'ultima7': 'Ultima VII: The Black Gate (1992)',
    'u7si': 'Ultima VII Part Two: Serpent Isle (1993)',
}


def pct(n: int, total: int) -> str:
    return '-' if not total else f'{100 * n / total:.2f}%'


def counts(d: dict[str, int]) -> str:
    """A count distribution as 'k A, k B', largest first, or '-'."""
    return ', '.join(f'{k} {v:,}' for k, v in sorted(d.items(), key=lambda kv: -kv[1])) if d else '-'


def mix_row(name: str, r: dict) -> str:
    c, t = r['by_class'], r['retired']
    # Every class, so the row sums to 100%: `round` is FRNDINT, which honours
    # rounding control and ignores precision control, and `simple` is FCHS,
    # FABS, FFREE and the stack moves.
    return (f"| {name} | {r['retired']:,} | "
            f"{pct(c.get('load', 0), t)} / {pct(c.get('store', 0), t)} / {pct(c.get('fxch', 0), t)} | "
            f"{pct(c.get('arith', 0), t)} | {pct(c.get('compare', 0), t)} | "
            f"{pct(c.get('trans', 0), t)} | {pct(c.get('round', 0), t)} | "
            f"{pct(c.get('simple', 0), t)} | {pct(c.get('control', 0), t)} |")


def pc_class(r: dict) -> str:
    """The committed PC class: 24, 53, 64, or mixed when more than one PC
    appears over the arithmetic forms."""
    present = [k for k, v in r['pc_arith'].items() if v]
    if not present:
        return '-'
    return present[0] if len(present) == 1 else 'mixed (' + ', '.join(sorted(present)) + ')'


def precision_row(name: str, r: dict) -> str:
    verdict = ('probe only, no verdict' if r['probe_only']
               else 'yes' if r['pc24_sufficient'] else '**no**')
    return (f"| {name} | {pc_class(r)} | {counts(r['pc_arith'])} | {counts(r['rc_arith'])} | "
            f"{counts({k: v for k, v in r['significand_excluding_register_stores'].items() if k in ('le53', 'le64')}) } | "
            f"{r['by_form'].get('db.m5', 0):,} / {r['by_form'].get('db.m7', 0):,} | {verdict} |")


def operand_row(name: str, r: dict) -> str:
    o = r['by_operand']
    return (f"| {name} | {o.get('real32', 0):,} | {o.get('real64', 0):,} | {o.get('real80', 0):,} | "
            f"{o.get('int16', 0):,} / {o.get('int32', 0):,} / {o.get('int64', 0):,} | "
            f"{o.get('bcd80', 0):,} | {o.get('image', 0):,} |")


def exception_row(name: str, r: dict) -> str:
    unmasked = {k: v for k, v in r['exception_masks'].items() if k != '3f'}
    return (f"| {name} | {counts(r['exception_masks'])} | {counts(unmasked) if unmasked else 'none'} | "
            f"{'yes' if r['es_set'] else 'no'} | {r['irq13']:,} | "
            f"{'yes' if r['relies_on_exceptions'] else 'no'} | "
            f"{counts(r['exceptions']) if r['exceptions'] else 'none'} |")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('runs', nargs='+', metavar='NAME=DIR')
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--jsonl', type=Path, required=True)
    args = parser.parse_args(argv)

    rows, missing = [], []
    for spec in args.runs:
        name, _, directory = spec.partition('=')
        row = summary.run(name, Path(directory))
        if row.get('missing'):
            missing.append(name)
            continue
        rows.append((name, row))
    args.jsonl.write_text(''.join(json.dumps(r, sort_keys=True) + '\n' for _, r in rows))

    out = ['# The x87 game census: per-title tables', '',
           'Generated by `scripts/pc386_x87_census_tables.py` from the census files;',
           'the rows are in [`census.jsonl`](census.jsonl). Every figure is of the',
           "title's own window, on the drive the method pins.", '']
    if missing:
        out += [f"Not run or no census file: {', '.join(missing)}.", '']

    def table(heading: str, header: str, rule: str, fn) -> None:
        out.extend(['## ' + heading, '', header, rule])
        for name, row in rows:
            out.append(fn(TITLES.get(name, name) + (f" ({row.get('seconds')} s)" if row.get('seconds') else ''),
                          row['x87']))
        out.append('')

    table('The opcode mix',
          '| Title | x87 retired | load / store / FXCH | arithmetic | compare | transc. | FRNDINT | simple | control |',
          '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |', mix_row)
    table('Precision control, rounding control, and the verdict',
          '| Title | PC class | PC over arithmetic | RC over arithmetic | significands above 24 bits (excl. register stores) | FLD m80 / FSTP m80 | 24-bit significand sufficient? |',
          '| --- | --- | --- | --- | --- | ---: | --- |', precision_row)
    table('The operand precisions actually used',
          '| Title | real m32 | real m64 | real m80 | int m16 / m32 / m64 | BCD m80 | env and save images |',
          '| --- | ---: | ---: | ---: | ---: | ---: | ---: |', operand_row)
    table('Exceptions',
          '| Title | control-word low byte (masks) | instructions with any exception unmasked | ES ever set | IRQ 13 delivered | relies on exceptions | flags raised |',
          '| --- | --- | --- | --- | ---: | --- | --- |', exception_row)

    # What the window reached, and the control word over it.
    out.extend(['## The window', '',
                "What each run ended on, and the precision and rounding control seen in",
                'each whole simulated second. A window that ends at `limit` ran out of',
                'time; `prompt` means the program returned to the DOS prompt.', '',
                '| Title | window (s) | ended on | control word by second |',
                '| --- | ---: | --- | --- |'])
    for name, row in rows:
        by_second = row['x87']['cw_by_second']
        text = '; '.join(f"{k} s: {', '.join(v)}" for k, v in list(by_second.items())[:6]) or '-'
        if len(by_second) > 6:
            text += f' … ({len(by_second)} seconds with x87)'
        out.append(f"| {TITLES.get(name, name)} | {row.get('seconds')} | {row.get('end')} | {text} |")
    out.append('')

    # Rounding control where it acts but precision control does not.
    out.extend(['## Rounding control on the stores and FRNDINT', '',
                'The integer and real stores and `FRNDINT` round under **rounding** control',
                'and ignore precision control, so a reduced unit would still have to honour',
                'the full rounding path on them.', '',
                '| Title | FRNDINT | FRNDINT by PC (which it ignores) | RC over all forms |',
                '| --- | ---: | --- | --- |'])
    for name, row in rows:
        r = row['x87']
        out.append(f"| {TITLES.get(name, name)} | {r['frndint']:,} | "
                   f"{counts(r['frndint_by_pc'])} | {counts(r['rc_all'])} |")
    out.append('')

    # What the titles store: wide values by the width of the slot they went to.
    # x87sig reads the state before a popping store, so this is the value
    # stored. A store to m32 rounds to 24 bits under rounding control whatever
    # the register held, so that column cannot settle anything by itself.
    # What the titles store: wide values by what they were stored AS.
    # x87sig reads the state before a popping store, so this is the value
    # stored. Integer conversions are kept apart from real stores: FIST and
    # FISTP convert to an integer, so a wide source significand is not
    # evidence about the width of a floating-point datapath in the way a real
    # store is. A store to m32 rounds to 24 bits under rounding control
    # whatever the register held, so it cannot settle anything either.
    REAL64 = ('dd.m2', 'dd.m3')
    REAL80 = ('db.m7',)
    REAL32 = ('d9.m2', 'd9.m3')
    INTEGER = ('db.m2', 'db.m3', 'df.m2', 'df.m3', 'df.m6', 'df.m7')
    out.extend(['## What the titles store', '',
                'Stored values whose significand needs more than 24 bits, by what they were',
                'stored as. **Only the real m64 and m80 columns are evidence** that a',
                '24-bit datapath could not have produced the bytes in memory.', '',
                '- **real m32** rounds to 24 bits under rounding control whatever the',
                '  register held, so a wide register value may land on exactly the bytes a',
                '  24-bit unit would have written.',
                '- **real m64 is split by source width.** An m64 destination rounds the',
                "  source's significand to 53 bits, so an `le53` source is stored exactly and",
                '  is the measured figure. An `le64` source is rounded in the store; its',
                '  stored value still exceeds 24 bits except where the rounding happens to',
                '  leave trailing zeros, so that column is a sound inference rather than a',
                '  measurement, and is kept separate.',
                '- **integer** is `FIST`/`FISTP`/`FBSTP`: a conversion to an integer or BCD,',
                '  so a wide source significand says nothing about the width a',
                '  floating-point datapath needs to hold the result.',
                '- `FST`/`FSTP ST(i)` move no memory operand and are not here; their own',
                "  width buckets in these runs are unreliable (see the record's note).", '',
                '| Title | **real m64, preserved exactly** | real m64, rounded in the store | **real m80** | real m32 (rounds) | integer conversions |',
                '| --- | ---: | ---: | ---: | ---: | ---: |'])
    for name, row in rows:
        r = row['x87']
        def wide(forms, buckets=('le53', 'le64')):
            return sum(v for bucket, fs in r['significand_forms'].items() if bucket in buckets
                       for f, v in fs.items() if f in forms)
        # An m64 destination rounds the source's significand to 53 bits, so an
        # le53 source is preserved exactly and is the measured figure; an le64
        # source is rounded in the store, and that its rounded value still
        # exceeds 24 bits is an inference, not a measurement.
        out.append(f"| {TITLES.get(name, name)} | {wide(REAL64, ('le53',)):,} | "
                   f"{wide(REAL64, ('le64',)):,} | {wide(REAL80):,} | "
                   f"{wide(REAL32):,} | {wide(INTEGER):,} |")
    out.append('')

    out.extend(['## FSQRT by precision control', '',
                'For slice 6: square-root early termination saves 12 clocks at PC=24 and',
                'costs 37 bits of remainder width on every square root.', '',
                '| Title | FSQRT | by PC |', '| --- | ---: | --- |'])
    for name, row in rows:
        r = row['x87']
        out.append(f"| {TITLES.get(name, name)} | {r['fsqrt']:,} | {counts(r['fsqrt_by_pc'])} |")
    out.extend(['', '## Calibration', '',
                'Σ`x87op` against the D8-DF stem total in the same census file, with the',
                'ESC steps that faulted or were held by the BUSY# latch, which sit outside',
                'both.', '', '| Title | Σ x87op | D8-DF stems | equal | faulted | held |',
                '| --- | ---: | ---: | --- | ---: | ---: |'])
    for name, row in rows:
        c = row['x87']['calibration']
        out.append(f"| {TITLES.get(name, name)} | {c['x87op_total']:,} | {c['esc_stem_total']:,} | "
                   f"{'yes' if c['x87op_total'] == c['esc_stem_total'] else '**no**'} | "
                   f"{c['faulted']:,} | {c['held']:,} |")
    out.append('')

    # Every form that executed, and -- for slice 6 -- the forms no title did.
    forms = sorted({f for _, row in rows for f in row['x87']['by_form']})
    out.extend(['## Every form that executed', '',
                'The full histogram, not a top-N: the forms that decide a design question',
                'are not always the frequent ones. `class` and `operand` are',
                "`pc386_census_summary.py`'s classification.", '',
                '| Form | class | operand | ' + ' | '.join(TITLES.get(n, n) for n, _ in rows) + ' |',
                '| --- | --- | --- | ' + ' | '.join('---:' for _ in rows) + ' |'])
    for form in forms:
        cls, operand = X_UNKNOWN if form not in summary.X87_FORMS else summary.X87_FORMS[form]
        out.append(f'| `{form}` | {cls} | {operand} | ' +
                   ' | '.join(f"{row['x87']['by_form'].get(form, 0):,}" for _, row in rows) + ' |')
    # The 387 instructions no title executed, named rather than counted as a
    # fraction: the denominator of key spellings is not meaningful, because the
    # table holds spellings the census cannot emit and encodings that are not
    # 387 instructions.
    never = sorted(f for f in summary.X87_FORMS if f not in forms and f in summary.X87_MNEMONIC)
    unnamed = sorted(f for f in summary.X87_FORMS if f not in forms and f not in summary.X87_MNEMONIC)
    out.extend(['', '**The 387 instructions no title in this census executed**, over all '
                    f'{len(rows)} runs:', ''])
    for form in never:
        out.append(f'- {summary.x87_name(form)}')
    out.extend(['', f'A further {len(unnamed)} register-form spellings in the classification '
                    'went unexecuted; they are the `ST(i)` variants of forms above and '
                    'encodings the census cannot emit, so they are not listed as '
                    'instructions.',
                '', 'For slice 6: the named instructions above are what the census titles never',
                'reach, so optimising them buys nothing measurable here. They must still be',
                '*correct* — a 387 that is missing a form is not a 387 — but they need not be',
                'fast. The caveat is the window\'s: a title that reaches one only in later',
                'play is not represented.', ''])
    args.out.write_text('\n'.join(out))
    print(f'{len(rows)} rows -> {args.out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
