"""The x87 game census's tables, from pc386_census_summary.py's rows.

    python3 scripts/pc386_x87_census_tables.py --out docs/validation/.../tables.md \
        --jsonl docs/validation/.../census.jsonl quake=build/sim/fes-pc386/game-quakes-x87 ...

Writes one JSON row per run and the record's Markdown tables. The rows hold
counts only: no instruction bytes, frames or game data. The verdict column is
pc24_sufficient from the summary, not a reading of the other columns.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pc386_census_summary as summary  # noqa: E402

X_UNKNOWN = ('unknown', 'unknown')

TITLES = {
    'quake': 'Quake timedemo (DOSBench)', 'screamer': 'Screamer (1995)',
    'chrisb': "Chris's 3D Benchmark", 'tv': 'Terminal Velocity (1995)',
    'doom': 'DOOM (1993)', 'wolf3d': 'Wolfenstein 3D (1992)',
    'ultima6': 'Ultima VI: The False Prophet (1990)',
    'ultima7': 'Ultima VII: The Black Gate (1992)',
    'u7si': 'Ultima VII Part Two: Serpent Isle (1993)',
}


def pct(n: int, total: int) -> str:
    return '-' if not total else f'{100 * n / total:.2f}%'


def counts(d: dict[str, int]) -> str:
    """A count distribution as 'k A, k B', largest first, or '-'."""
    return ', '.join(f'{k} {v:,}' for k, v in sorted(d.items(), key=lambda kv: -kv[1])) if d else '-'


def mix_row(name: str, r: dict) -> str:
    c, t = r['by_class'], r['retired']
    return (f"| {name} | {r['retired']:,} | "
            f"{pct(c.get('load', 0), t)} / {pct(c.get('store', 0), t)} / {pct(c.get('fxch', 0), t)} | "
            f"{pct(c.get('arith', 0), t)} | {pct(c.get('compare', 0), t)} | "
            f"{pct(c.get('trans', 0), t)} | {pct(c.get('control', 0), t)} |")


def precision_row(name: str, r: dict) -> str:
    verdict = ('probe only, no verdict' if r['probe_only']
               else 'yes' if r['pc24_sufficient'] else '**no**')
    return (f"| {name} | {counts(r['pc_arith'])} | {counts(r['rc_arith'])} | "
            f"{counts({k: v for k, v in r['significand'].items() if k in ('le53', 'le64')}) } | "
            f"{r['by_form'].get('db.m5', 0):,} / {r['by_form'].get('db.m7', 0):,} | {verdict} |")


def operand_row(name: str, r: dict) -> str:
    o = r['by_operand']
    return (f"| {name} | {o.get('real32', 0):,} | {o.get('real64', 0):,} | {o.get('real80', 0):,} | "
            f"{o.get('int16', 0):,} / {o.get('int32', 0):,} / {o.get('int64', 0):,} | "
            f"{o.get('bcd80', 0):,} | {o.get('image', 0):,} |")


def exception_row(name: str, r: dict) -> str:
    unmasked = {k: v for k, v in r['exception_masks'].items() if k != '3f'}
    return (f"| {name} | {counts(r['exception_masks'])} | {counts(unmasked) if unmasked else 'none'} | "
            f"{'yes' if r['es_set'] else 'no'} | {counts(r['exceptions']) if r['exceptions'] else 'none'} |")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('runs', nargs='+', metavar='NAME=DIR')
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--jsonl', type=Path, required=True)
    args = parser.parse_args(argv)

    rows, missing = [], []
    for spec in args.runs:
        name, _, directory = spec.partition('=')
        row = summary.run(name, Path(directory))
        if row.get('missing'):
            missing.append(name)
            continue
        rows.append((name, row))
    args.jsonl.write_text(''.join(json.dumps(r, sort_keys=True) + '\n' for _, r in rows))

    out = ['# The x87 game census: per-title tables', '',
           'Generated by `scripts/pc386_x87_census_tables.py` from the census files;',
           'the rows are in [`census.jsonl`](census.jsonl). Every figure is of the',
           "title's own window, on the drive the method pins.", '']
    if missing:
        out += [f"Not run or no census file: {', '.join(missing)}.", '']

    def table(heading: str, header: str, rule: str, fn) -> None:
        out.extend(['## ' + heading, '', header, rule])
        for name, row in rows:
            out.append(fn(TITLES.get(name, name) + (f" ({row.get('seconds')} s)" if row.get('seconds') else ''),
                          row['x87']))
        out.append('')

    table('The opcode mix',
          '| Title | x87 retired | load / store / FXCH | arithmetic | compare | transcendental | control |',
          '| --- | ---: | ---: | ---: | ---: | ---: | ---: |', mix_row)
    table('Precision control, rounding control, and the verdict',
          '| Title | PC over arithmetic | RC over arithmetic | significands above 24 bits | FLD m80 / FSTP m80 | 24-bit significand sufficient? |',
          '| --- | --- | --- | --- | ---: | --- |', precision_row)
    table('The operand precisions actually used',
          '| Title | real m32 | real m64 | real m80 | int m16 / m32 / m64 | BCD m80 | env and save images |',
          '| --- | ---: | ---: | ---: | ---: | ---: | ---: |', operand_row)
    table('Exceptions',
          '| Title | control-word low byte (masks) | instructions with any exception unmasked | ES ever set | flags raised |',
          '| --- | --- | --- | --- | --- |', exception_row)

    # What the window reached, and the control word over it.
    out.extend(['## The window', '',
                "What each run ended on, and the precision and rounding control seen in",
                'each whole simulated second. A window that ends at `limit` ran out of',
                'time; `prompt` means the program returned to the DOS prompt.', '',
                '| Title | window (s) | ended on | control word by second |',
                '| --- | ---: | --- | --- |'])
    for name, row in rows:
        by_second = row['x87']['cw_by_second']
        text = '; '.join(f"{k} s: {', '.join(v)}" for k, v in list(by_second.items())[:6]) or '-'
        if len(by_second) > 6:
            text += f' … ({len(by_second)} seconds with x87)'
        out.append(f"| {TITLES.get(name, name)} | {row.get('seconds')} | {row.get('end')} | {text} |")
    out.append('')

    # Rounding control where it acts but precision control does not.
    out.extend(['## Rounding control on the stores and FRNDINT', '',
                'The integer and real stores and `FRNDINT` round under **rounding** control',
                'and ignore precision control, so a reduced unit would still have to honour',
                'the full rounding path on them.', '',
                '| Title | FRNDINT | FRNDINT by PC (which it ignores) | RC over all forms |',
                '| --- | ---: | --- | --- |'])
    for name, row in rows:
        r = row['x87']
        out.append(f"| {TITLES.get(name, name)} | {r['by_form'].get('d9fc', 0):,} | "
                   f"{counts(r['pc_by_class'].get('other', {}))} | {counts(r['rc_all'])} |")
    out.append('')

    out.extend(['## FSQRT by precision control', '',
                'For slice 6: square-root early termination saves 12 clocks at PC=24 and',
                'costs 37 bits of remainder width on every square root.', '',
                '| Title | FSQRT | by PC |', '| --- | ---: | --- |'])
    for name, row in rows:
        r = row['x87']
        out.append(f"| {TITLES.get(name, name)} | {r['fsqrt']:,} | {counts(r['fsqrt_by_pc'])} |")
    out.extend(['', '## Calibration', '',
                'Σ`x87op` against the D8-DF stem total in the same census file, with the',
                'ESC steps that faulted or were held by the BUSY# latch, which sit outside',
                'both.', '', '| Title | Σ x87op | D8-DF stems | equal | faulted | held |',
                '| --- | ---: | ---: | --- | ---: | ---: |'])
    for name, row in rows:
        c = row['x87']['calibration']
        out.append(f"| {TITLES.get(name, name)} | {c['x87op_total']:,} | {c['esc_stem_total']:,} | "
                   f"{'yes' if c['x87op_total'] == c['esc_stem_total'] else '**no**'} | "
                   f"{c['faulted']:,} | {c['held']:,} |")
    out.append('')

    # Every form that executed, and -- for slice 6 -- the forms no title did.
    forms = sorted({f for _, row in rows for f in row['x87']['by_form']})
    out.extend(['## Every form that executed', '',
                'The full histogram, not a top-N: the forms that decide a design question',
                'are not always the frequent ones. `class` and `operand` are',
                "`pc386_census_summary.py`'s classification.", '',
                '| Form | class | operand | ' + ' | '.join(TITLES.get(n, n) for n, _ in rows) + ' |',
                '| --- | --- | --- | ' + ' | '.join('---:' for _ in rows) + ' |'])
    for form in forms:
        cls, operand = X_UNKNOWN if form not in summary.X87_FORMS else summary.X87_FORMS[form]
        out.append(f'| `{form}` | {cls} | {operand} | ' +
                   ' | '.join(f"{row['x87']['by_form'].get(form, 0):,}" for _, row in rows) + ' |')
    never = sorted(set(summary.X87_FORMS) - set(forms))
    out.extend(['', f'**Forms no title in this census executed ({len(never)} of '
                    f'{len(summary.X87_FORMS)}):** ' + ', '.join(f'`{f}`' for f in never) + '.',
                '', 'For slice 6: these are the forms the census titles never reach, so',
                'optimising them buys nothing measurable here. They must still be *correct* —',
                'a 387 that is missing a form is not a 387 — but they need not be fast.', ''])
    args.out.write_text('\n'.join(out))
    print(f'{len(rows)} rows -> {args.out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
