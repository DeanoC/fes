#!/usr/bin/env python3
"""Write results.md for x87 slice 6.3 from the committed fit evidence (method.md).

  python3 generate.py            # rewrites results.md
  python3 generate.py --check    # fails if results.md is stale

Every fit is read from fits/<name>/. The baseline is #2037's four head seeds,
quoted from that PR's record. The rules are method.md's, applied mechanically.
"""
import argparse
import csv
import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FITS = HERE / 'fits'
# #2037's head seeds: docs/validation/2026-11-20-i386-x87-s6-remainder/fits/head-s{1..4}/fit.json.
BASELINE = {1: 42_565, 2: 42_599, 3: 42_583, 4: 42_570}
LINE_92, DEVICE = 43_056, 46_800
SHELL = 7_728              # #2036's controlled pair: board less the virtual-pin envelope (amendment 1)
SHELL_ESTIMATE = 8_400     # quoted beside it for continuity
BOUNDS = (('bcd', 'FBLD and FBSTP removed (ablation-bcd.patch)'),
          ('fast', 'fast lane collapsed to one registered stage (ablation-fastlane.patch)'),
          ('fast2', 'fast lane with one register boundary after stage 3 (ablation-fastlane2.patch)'))


def load(name: str) -> dict | None:
    d = FITS / name
    if not (d / 'fit.json').is_file():
        return None
    fit = json.loads((d / 'fit.json').read_text())
    rows = [r for r in csv.DictReader((d / 'timing.tsv').open(), delimiter='\t')
            if r['check'] == 'clk_clock_setup' and r['worst_slack_ns'] not in ('', 'None')]
    timing = fit['timing']
    r = fit['resources']
    return {'name': name, 'seed': fit['seed'], 'fit': fit['status'],
            'timing': timing['status'] if isinstance(timing, dict) else timing,
            'alms': r['alms']['used'], 'ram': r['ram_blocks']['used'], 'dsp': r['dsp_blocks']['used'],
            'regs': r['registers']['used'],
            'setup': min(float(x['worst_slack_ns']) for x in rows) if rows else None}


def board_rows(median: float) -> list[str]:
    out = ['| Shell | Board estimate | Against the 92% line | Against the device |', '| ---: | ---: | ---: | ---: |']
    for shell, label in ((SHELL, f'{SHELL:,} (measured)'), (SHELL_ESTIMATE, f'{SHELL_ESTIMATE:,} (estimate)')):
        board = median + shell
        out.append(f'| {label} | {board:,.1f} | {board - LINE_92:+,.1f} | {board - DEVICE:+,.1f} |')
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    base = list(BASELINE.values())
    m_base, s_base = statistics.median(base), max(base) - min(base)
    lines = ['# x87 slice 6.3: results', '', '<!-- generated by generate.py from fits/; do not edit -->', '',
             'Rules: [method.md](method.md). The baseline is #2037\'s four head seeds '
             f'({", ".join(f"{v:,}" for v in base)}; median {m_base:,.1f}, spread {s_base}).', '',
             '## The bounds, by ablation', '',
             '| Ablation | Seeds | ALMs needed | Median | Spread | Bound (baseline − median) | Larger spread | '
             'Measurable | Worst setup at 61.44 MHz | RAM | DSP |',
             '| --- | ---: | --- | ---: | ---: | ---: | ---: | --- | --- | ---: | ---: |']
    for name, what in BOUNDS:
        rows = [r for r in (load(f'{name}-s{s}') for s in (1, 2, 3, 4)) if r]
        if not rows:
            continue
        alms = [r['alms'] for r in rows]
        med, spread = statistics.median(alms), max(alms) - min(alms)
        floor = max(spread, s_base)
        bound = m_base - med
        timing = 'all pass' if all(r['fit'] == 'pass' and r['timing'] == 'pass' for r in rows) else 'A MISS'
        setups = [r['setup'] for r in rows if r['setup'] is not None]
        lines.append(f"| {what} | {len(rows)} | {', '.join(f'{a:,.0f}' for a in alms)} | {med:,.1f} | {spread:,.0f} | "
                     f"**{bound:+,.1f}** | {floor:,.0f} | {'yes' if bound > floor else 'no'} | {timing}, "
                     f"{min(setups):+.3f} to {max(setups):+.3f} ns | {', '.join(sorted({f'{r['ram']:.0f}' for r in rows}))} | "
                     f"{', '.join(sorted({f'{r['dsp']:.0f}' for r in rows}))} |")
    lines += ['', 'The baseline\'s own worst setup was +7.715 to +8.071 ns (#2037\'s head fits). BCD seed 2\'s '
              'first fitter was killed by signal 9 under host memory pressure while it read the SDC '
              '([fits/bcd-s2-killed/fit.log](fits/bcd-s2-killed/fit.log)); the seed was rerun on the same netlist '
              '([run-status.txt](run-status.txt)) and only the rerun is counted.', '',
              '## Where the head stands on the real board', '',
              f'From the head\'s median ({m_base:,.1f}) plus the shell, which #2036\'s pair measured as the board less '
              'the virtual-pin envelope, so nothing is subtracted for virtual pins (method.md, amendment 1):', '']
    lines += board_rows(m_base)
    text = '\n'.join(lines).rstrip() + '\n'
    out = HERE / 'results.md'
    if args.check:
        if not out.is_file() or out.read_text() != text:
            print('results.md is stale; run generate.py', file=sys.stderr)
            return 1
        return 0
    out.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
