HERE = Path(__file__).resolve().parent
CENSUS = HERE.parent / '2026-11-15-i386-x87-game-census' / 'census.jsonl'

# The instructions this step builds, in the plan record's slice 5 order
# (docs/validation/2026-11-12-i386-x87-plan/summary.md, "Slices"), with the
# census's key for each form (pc386_census_summary.py's naming: the opcode
# byte and ModRM byte of a register form, the opcode and reg field of a
# memory form).
FORMS = (
    ('FSIN', 'd9fe'), ('FCOS', 'd9ff'), ('FSINCOS', 'd9fb'), ('FPTAN', 'd9f2'),
    ('FPATAN', 'd9f3'), ('F2XM1', 'd9f0'), ('FYL2X', 'd9f1'), ('FYL2XP1', 'd9f9'),
    ('FBLD', 'df.m4'), ('FBSTP', 'df.m6'),
)


def census_rows() -> list[dict]:
    rows = []
    for line in CENSUS.read_text().splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        x87 = dict(row['x87']) if isinstance(row['x87'], list) else row['x87']
        rows.append({'title': row['title'], 'seconds': row['seconds'],
                     'by_form': x87.get('by_form', {}),
                     'total': x87.get('calibration', {}).get('x87op_total', 0)})
    return rows


def demand() -> str:
    rows = census_rows()
    titles = [row['title'] for row in rows]
    out = ['# What the census titles ask of this step', '',
           '<!-- generated by generate.py from the game census\'s census.jsonl; do not edit -->', '',
           f'Counts of each instruction this step builds, over the {len(rows)} runs of the game census',
           '([record](../2026-11-15-i386-x87-game-census/summary.md), PR #1887). A count is x87',
           'instructions retired in that run\'s window on the Bochs oracle with a 387 fitted; a title',
           'that reaches a form only in later play is not represented.', '',
           '| Instruction | Census key | ' + ' | '.join(titles) + ' | Runs executing it | Total |',
           '| --- | --- | ' + ' | '.join('---:' for _ in titles) + ' | ---: | ---: |']
    totals = {}
    for name, key in FORMS:
        counts = [row['by_form'].get(key, 0) for row in rows]
        totals[name] = (sum(counts), sum(1 for c in counts if c))
        out.append(f'| {name} | `{key}` | ' + ' | '.join(f'{c:,}' for c in counts)
                   + f' | {totals[name][1]} | {totals[name][0]:,} |')
    out += ['', '| Run | Window (s) | x87 instructions | Of which this step\'s forms | Share |',
            '| --- | ---: | ---: | ---: | ---: |']
    for row in rows:
        mine = sum(row['by_form'].get(key, 0) for _, key in FORMS)
        share = f'{100 * mine / row["total"]:.3f}%' if row['total'] else '-'
        out.append(f'| {row["title"]} | {row["seconds"]:g} | {row["total"]:,} | {mine:,} | {share} |')
    ordered = sorted(FORMS, key=lambda form: (-totals[form[0]][1], -totals[form[0]][0]))
    reached = [name for name, _ in ordered if totals[name][0]]
    unreached = [name for name, _ in FORMS if not totals[name][0]]
    out += ['', '**Order of work, by census demand** (runs executing the form, then total count): '
            + ', '.join(f'{name} ({totals[name][1]} run{'' if totals[name][1] == 1 else 's'}, {totals[name][0]:,})' for name in reached) + '.', '',
            '**Forms no title in the census executes:** ' + (', '.join(unreached) if unreached else 'none') + '.',
            'They are built because a 387 missing a form is not a 387, and they serve no measured demand.', '']
    return '\n'.join(out)


def _load(name: str):
    path = HERE / 'evidence' / name
    return json.loads(path.read_text()) if path.is_file() else None


BINS = ('0', '1', '2', '4', '16', '256', '65536')


def _binned(histogram: dict) -> list[int]:
    """An exact-distance histogram into the bins the probes use: each value
    in the smallest bin whose edge it is within, the last column the rest."""
    counts = [0] * (len(BINS) + 1)
    for distance, count in histogram.items():
        index = next((n for n, edge in enumerate(BINS) if int(distance) <= int(edge)), len(BINS))
        counts[index] += count
    return counts


def references() -> str:
    """The measured distances the proposed bounds rest on, whole histograms."""
    probe, hosts = _load('reference-probe.json'), _load('host-comparison.json')
    models = [(_load('model-vs-host-intel.json'), 'Intel'), (_load('model-vs-host-amd.json'), 'AMD')]
    out = ['# The references against each other, and the model against them', '',
           '<!-- generated by generate.py from evidence/*.json; do not edit -->', '',
           'Distances are in representable extended values (method.md, rule 3). Every table is the',
           'whole histogram: each result is counted once, in the smallest bin it fits. Operand class',
           '-1 is the operands of QEMU\'s bracket tables; the other classes are the probe\'s random',
           'classes, named in the first table. **No table here involves the RTL.**', '']
    header = '| Instruction | Class | Values | ' + ' | '.join(f'<= {b}' if b != '0' else '0' for b in BINS) \
        + ' | more | Not a distance | Worst |'
    rule = '| --- | --- | ---: | ' + ' | '.join('---:' for _ in BINS) + ' | ---: | ---: | ---: |'
    if probe:
        out += ['## The Bochs oracle against the host x87', '',
                f'Host: {probe["host_cpu"]}. Revision `{probe["source"]["fes_revision"][:9]}`, '
                f'{probe["samples_per_class"]:,} operands a class. Flags and C0, C2, C3 differed on '
                f'**{sum(c["flags_differ"] + c["c0_c2_c3_differ"] for cl in probe["instructions"].values() for c in cl)}** '
                'operands; C1 on '
                f'{sum(c["c1_differ"] for cl in probe["instructions"].values() for c in cl):,}.', '', header, rule]
        for name, classes in probe['instructions'].items():
            for index, c in enumerate(classes):
                cumulative = [c['distance_at_most'][b] for b in BINS] + [c['distance_at_most']['any']]
                each = [cumulative[0]] + [cumulative[n] - cumulative[n - 1] for n in range(1, len(cumulative))]
                values = cumulative[-1] + c['not_a_distance']
                label = c['class'].replace('|', '\\|')
                out.append(f'| {name} | {index}: {label} | {values:,} | ' + ' | '.join(f'{v:,}' for v in each)
                           + f' | {c["not_a_distance"]:,} | {c["worst_distance"]:.3g} |')
        out += ['', '## Each reference against QEMU\'s brackets of the mathematical result', '',
                f'QEMU `{probe["qemu"]["revision"][:9]}`; the tables are fetched at run time and not committed. '
                'The distance is how far outside the bracket a result lies, 0 being one of the two neighbours of '
                'the mathematical result.', '',
                '| Instruction | Reference | Rows | ' + ' | '.join(f'<= {b}' if b != '0' else 'inside' for b in BINS)
                + ' | more | Worst |', '| --- | --- | ---: | ' + ' | '.join('---:' for _ in BINS) + ' | ---: | ---: |']
        for name, row in probe['brackets'].items():
            for side in ('oracle', 'host'):
                c = row[side]
                cumulative = [c['outside_at_most'][b] for b in BINS] + [c['outside_at_most']['any']]
                each = [cumulative[0]] + [cumulative[n] - cumulative[n - 1] for n in range(1, len(cumulative))]
                out.append(f'| {name} | {side} | {row["count"]:,} | ' + ' | '.join(f'{v:,}' for v in each)
                           + f' | {c["worst_outside"]:.3g} |')
    if hosts:
        a, b = hosts['hosts']
        out += ['', '## The two build hosts against each other', '',
                f'{a["cpu"]} against {b["cpu"]}, {a["rows"]:,} operand rows each. Flags and C0, C2, C3 differed on '
                f'**{sum(c["flags_differ"] + c["c0_c2_c3_differ"] for c in hosts["classes"])}** rows; C1 on '
                f'{sum(c["c1_differ"] for c in hosts["classes"]):,}.', '', header, rule]
        for c in hosts['classes']:
            each = [c['distance'][b] for b in BINS] + [c['distance']['more']]
            out.append(f'| {c["instruction"]} | {c["class"]} | {c["values"]:,} | ' + ' | '.join(f'{v:,}' for v in each)
                       + f' | {c["not_a_distance"]:,} | {c["worst_distance"]} |')
    for model, cpu in models:
        if not model:
            continue
        out += ['', f'## The microprogram\'s model against the {cpu} host', '',
                f'{model["dump"]["header"]}. Model `{model["model_sha256"][:12]}`, {model["microprogram_words"]} '
                f'microprogram words, {model["constants"]} constants. Rows the unit answers without the engine '
                '(a zero, an operand out of range) are not the model\'s and are counted apart. The error columns '
                'are the model against the mathematical result, in units of the last place, before and after its '
                'last rounding.', '',
                '| Instruction | Class | Compared | Outside the engine | ' + ' | '.join(
                    f'<= {b}' if b != '0' else '0' for b in BINS) + ' | more | Not a distance | Worst | Error before | '
                'Error after | Backend operations, most |',
                '| --- | --- | ---: | ---: | ' + ' | '.join('---:' for _ in BINS)
                + ' | ---: | ---: | ---: | ---: | ---: | ---: |']
        for c in model['classes']:
            each = _binned(c['host_distance'])
            errors = ['-' if c[k] is None else f'{c[k]:.3f}' for k in ('error_before_rounding', 'error_after_rounding')]
            out.append(f'| {c["instruction"]} | {c["class"]} | {c["compared"]:,} | {c["outside_engine"]:,} | '
                       + ' | '.join(f'{v:,}' for v in each)
                       + f' | {c["not_a_distance"]:,} | {c["worst_host_distance"]} | {errors[0]} | {errors[1]} | '
                       f'{c["backend_operations_most"]} |')
    return '\n'.join(out) + '\n'


FINAL = HERE / 'evidence' / 'final'


def _final(name: str):
    path = FINAL / name
    return json.loads(path.read_text()) if path.is_file() else None


def _source(report: dict) -> str:
    source = report.get('source') or {}
    changes = source.get('tracked_changes')
    return (f'`{source.get("fes_revision", "unknown")[:9]}`'
            + ('' if changes == [] else f', **{len(changes or [])} tracked files differing**' if changes else ''))


def results() -> str:
    """What was run on the final head, from the reports under evidence/final."""
    out = ['# Results on the final head', '',
           '<!-- generated by generate.py from evidence/final/*.json; do not edit -->', '',
           'Every row names the revision its report says it tested. A report that is missing is',
           'printed as not run, not left out.', '']
    out += ['## The unit bench, against the host x87', '',
            '| Configuration | Revision | Cases | Passed | Failed | Packed decimal cases | Transcendental cases | '
            'Model vectors, exact | Bound against the host |',
            '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |']
    units = {}
    for backend in ('de10', 'de25'):
        for kind in ('rtl', 'netlist'):
            report = _final(f'unit-{backend}-{kind}.json')
            units[(backend, kind)] = report
            label = f'{"DE10 sequencer" if backend == "de10" else "DE25 backend"}, {"RTL" if kind == "rtl" else "locked-Yosys netlist"}'
            if not report:
                out.append(f'| {label} | **not run** | | | | | | | |')
                continue
            trans = report.get('transcendentals') or {}
            bound = trans.get('bound_host')
            out.append(f'| {label} | {_source(report)} | {report["cases"]:,} | {report["passed"]:,} | '
                       f'{report["failed"]:,} | {report["bcd_cases"]:,} | {trans.get("cases", 0):,} | '
                       f'{trans.get("model_vectors_compared_exactly", 0):,} | '
                       + ('-' if not trans else f'{bound} (proposed, not agreed)' if bound is not None else 'unset') + ' |')
    for (backend, kind), report in units.items():
        trans = (report or {}).get('transcendentals')
        if backend != 'de25' or not trans:
            continue
        out += ['', f'### The unit\'s results against the host\'s, DE25 backend, {"RTL" if kind == "rtl" else "netlist"}', '',
                'The whole histogram of the distance, in representable values, between each transcendental result',
                'and the host\'s. "Manual" counts the cases that follow the 387 manual where the host does otherwise.',
                '`C1 differs` is counted and not gated (method.md, amendment 2).', '',
                '| Instruction | Cases | Entered the engine | Results | Identical | Distance: count | Worst | '
                'C1 differs | Manual |', '| --- | ---: | ---: | ---: | ---: | --- | ---: | ---: | ---: |']
        for name, row in trans['instructions'].items():
            hist = ', '.join(f'{d}: {c:,}' for d, c in sorted(row['distance'].items(), key=lambda kv: int(kv[0])))
            out.append(f'| {name} | {row["cases"]:,} | {row["engine_runs"]:,} | {row["values"]:,} | '
                       f'{row["identical"]:,} | {hist} | {row["worst"]} | {row["c1_differs"]:,} | {row["manual"]:,} |')
        out += ['', f'Reset and squash sweep: {trans["reset_and_squash_offsets_inside_engine"]} offsets landed inside '
                'the engine.']
        qemu = trans.get('qemu_brackets')
        if qemu:
            out += ['', f'QEMU\'s bracket tables on the unit (`tests/tcg/i386` at `{qemu["revision"][:9]}`, '
                    f'{qemu["license"]}, fetched at run time and not committed). A result is inside when it is one '
                    'of the two extended values that bracket the mathematical result.', '',
                    '| Instruction | Rows | Inside | Distance outside: count | Worst |', '| --- | ---: | ---: | --- | ---: |']
            for name, row in qemu['instructions'].items():
                hist = ', '.join(f'{d}: {c:,}' for d, c in sorted(row['outside'].items(), key=lambda kv: int(kv[0])))
                out.append(f'| {name} | {row["rows"]:,} | {row["inside"]:,} | {hist} | {row["worst_outside"]} |')
        else:
            out += ['', 'QEMU\'s bracket tables: **not run** in this report.']
    forms = (units.get(('de25', 'rtl')) or {}).get('bcd_forms')
    if forms:
        out += ['', '### Packed decimal, DE25 backend, RTL', '',
                '| Instruction | Issued | Conversions entered |', '| --- | ---: | ---: |']
        out += [f'| {name.upper()} | {row["issued"]:,} | {row["converted"]:,} |' for name, row in forms.items()]
    engine = _final('engine.json')
    out += ['', '## The engine against its model, bit for bit', '']
    if engine:
        per = ', '.join(f'{name} {count:,}' for name, count in engine['vectors_by_instruction'].items())
        out += [f'Revision {_source(engine)}: **{engine["passed"]:,} of {engine["vectors"]:,} vectors equal**, '
                f'{engine["failed"]:,} differing ({per}). The longest instruction took {engine["clocks_most"]} clocks '
                f'in the engine and the mean was {engine["clocks_mean"]}.']
    else:
        out += ['**Not run.**']
    return '\n'.join(out) + '\n'


SUITES = (('reset_store', 'reset and store'), ('directed_cases', 'directed'), ('unreal_cases', 'unreal'),
          ('pmode_cases', 'protected mode'), ('paging_cases', 'paging'), ('no387_cases', 'no-387'),
          ('x87_cases', 'x87'), ('memory_cases', 'memory'), ('x87_bcd_cases', 'packed decimal (new)'),
          ('x87_trans_cases', 'transcendentals (new)'))


def _suite(report: dict, key: str):
    entry = (report or {}).get(key) or {}
    summary = entry.get('summary', entry)
    if not summary or 'passed' not in summary:
        return None
    return summary


def lockstep() -> str:
    out = ['# Lockstep against the Bochs oracle, on the final head', '',
           '<!-- generated by generate.py from evidence/final and evidence/baseline; do not edit -->', '']
    runs = (('de10', 'rtl', 'DE10 sequencer, RTL, the whole default suite'),
            ('de25', 'rtl', 'DE25 backend, RTL, the whole default suite'),
            ('de10', 'netlist', 'DE10 sequencer, locked-Yosys netlist, the directed suites'),
            ('de25', 'netlist', 'DE25 backend, locked-Yosys netlist, the directed suites'))
    for backend, kind, label in runs:
        report = _final(f'lockstep-{backend}-{kind}.json')
        base = _load(f'baseline/lockstep-{backend}.json')
        out += [f'## {label}', '']
        if not report:
            out += ['**Not run.**', '']
            continue
        run = report['run']
        out += [f'Revision {_source(report)}. Verdict: **{"pass" if run["passed"] else "FAIL"}**; '
                f'`default_suite` {str(run["default_suite"]).lower()}; arguments '
                + ', '.join(f'{k}={v}' for k, v in run['arguments'].items() if v not in ('None', None)) + '.', '',
                '| Suite | Cases | Passed | Failed | Trace hash | Against the merge-base baseline |',
                '| --- | ---: | ---: | ---: | --- | --- |']
        for key, name in SUITES:
            now, then = _suite(report, key), _suite(base, key)
            if not now:
                out.append(f'| {name} | not run | | | | |')
                continue
            if not then:
                verdict = 'no such suite at the merge base'
            elif (then.get('runs'), then.get('trace_hash')) == (now.get('runs'), now.get('trace_hash')):
                verdict = 'same cases, same hash'
            else:
                verdict = f'**differs**: baseline {then.get("runs")} cases, `{then.get("trace_hash")}`'
            out.append(f'| {name} | {now.get("runs", "")} | {now["passed"]} | {now["failed"]} | '
                       f'`{now.get("trace_hash", "")}` | {verdict} |')
        for key, name in (('corpus', 'corpus files'), ('random', 'random seeds')):
            now = (report.get(key) or {}).get('trace_hashes') or {}
            then = ((base or {}).get(key) or {}).get('trace_hashes') or {}
            if now and kind == 'rtl':
                same = sum(1 for k, v in now.items() if then.get(k) == v)
                out.append(f'| {name} | {len(now):,} | | | | {same:,} of {len(now):,} hashes equal the baseline\'s'
                           + ('' if same == len(now) == len(then) else f' (**baseline has {len(then):,}**)') + ' |')
        built = report.get('x87_built_forms')
        if built:
            out += ['', f'Built set, the bench\'s copy against the RTL\'s over {built["opcodes"]:,} x87 opcodes: '
                    f'{built["built"]["de10"]:,} built with the DE10 backend, {built["built"]["de25"]:,} with the '
                    f'DE25\'s, **{len(built["mismatches"]) if isinstance(built["mismatches"], list) else built["mismatches"]} mismatches**.']
        trans = (_suite(report, 'x87_trans_cases') or {}).get('x87_trans')
        bcd = (_suite(report, 'x87_bcd_cases') or {}).get('x87_bcd_forms')
        if bcd:
            out += ['', f'Packed decimal: FBLD stepped {bcd.get("fbld", 0):,} times, FBSTP {bcd.get("fbstp", 0):,}, '
                    f'stopped as not built {bcd.get("not_built", 0):,}.']
        if trans:
            bound = (report['x87_trans_cases'].get('bound') or {})
            out += ['', f'Transcendentals: bound against the oracle {bound.get("transcendental_ulp_oracle")} '
                    f'({bound.get("status")}); {trans.get("selftests", 0)} self-test checks of the compare rule; '
                    'every exception masked. "Unchecked" results are those the oracle returned outside the '
                    'trigonometric window (bound.md): everything but their value is still compared exactly.', '',
                    '| Instruction | Executed | Stopped as not built | Results within the bound | Worst | Unchecked | '
                    'Worst unchecked | Resynchronisations | C1 differs, ungated | Distance: count |',
                    '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |']
            for name, row in trans['forms'].items():
                hist = ', '.join(f'{d}: {c}' for d, c in sorted(row['histogram'].items(), key=lambda kv: int(kv[0])))
                out.append(f'| {name.upper()} | {row["executed"]:,} | {row["not_built"]:,} | {row["values"]:,} | '
                           f'{row["worst"]:,} | {row["unchecked"]:,} | {row["worst_unchecked"]:.3g} | '
                           f'{row["resyncs"]:,} | {row["c1_differs"]:,} | {hist or "-"} |')
            taken = (_suite(report, 'x87_trans_cases') or {}).get('divergence_retirements') or {}
            if taken:
                out += ['', 'Recorded divergences taken (divergences.toml): '
                        + ', '.join(f'`{k}` {v}' for k, v in sorted(taken.items())) + '.']
        out.append('')
    return '\n'.join(out) + '\n'


DEVICE_ALMS = 46800
BAND4_ALMS = 43056          # 92% of the device (method.md, the machine fit's bands)


def fits() -> str:
    """The machine fits against the bands method.md committed before them."""
    out = ['# The machine fits, against the precommitted bands', '',
           '<!-- generated by generate.py from fits/quartus.json and fits/timing.tsv; do not edit -->', '']
    path = HERE / 'fits' / 'quartus.json'
    if not path.is_file():
        return '\n'.join(out + ['**Not run.**', ''])
    records = {row['fit']: row for row in json.loads(path.read_text())['fits']}
    slack: dict = {}
    for line in (HERE / 'fits' / 'timing.tsv').read_text().splitlines()[1:]:
        fit, corner, _, check, coverage, _, worst = line.split('\t')[:7]
        if check in ('setup', 'hold') and worst not in ('null', ''):
            key = (fit, check)
            slack[key] = min(slack.get(key, float(worst)), float(worst))
    arms = (('trans', '**This work**: `pc386_system`, `x87_present = 1`, `X87_BACKEND = 1`'),
            ('base', '**The controlled baseline**: the same two scratch edits at the merge base'))
    medians, spreads = {}, {}
    for arm, label in arms:
        rows = [records.get(f'{arm}-s{seed}') for seed in (1, 2, 3, 4)]
        rows = [row for row in rows if row]
        source = rows[0]['netlist'].get('source_revision') if rows else None
        out += [f'## {label}', '',
                f'Netlist elaborated from `{str(source)[:9]}`; {rows[0]["device"] if rows else ""}, Quartus Pro '
                f'{rows[0]["quartus"] if rows else ""} on {rows[0]["host"] if rows else ""}, {rows[0]["period_ns"]:.3f} ns '
                '(61.44 MHz).' if rows else '**Not run.**', '',
                '| Seed | Fit | Timing, all corners | ALMs needed | of device | DSP | RAM blocks | Registers | '
                'LABs touched (spread, not fullness) | Worst setup | Worst hold |',
                '| ---: | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
        alms = []
        for row in rows:
            res = row['resources']
            used = int(res['alms']['used'])
            alms.append(used)
            def count(key):
                value = res.get(key)
                return int(value['used']) if isinstance(value, dict) else value
            out.append(f'| {row["seed"]} | {row["status"]} | {row["timing_status"]} | {used:,} | '
                       f'{100 * used / DEVICE_ALMS:.2f}% | {count("dsp_blocks")} | {count("ram_blocks")} | '
                       f'{count("registers"):,} | {count("labs"):,} | '
                       f'{slack.get((row["fit"], "setup"), float("nan")):+.3f} ns | '
                       f'{slack.get((row["fit"], "hold"), float("nan")):+.3f} ns |')
        if alms:
            ordered = sorted(alms)
            medians[arm] = (ordered[(len(ordered) - 1) // 2] + ordered[len(ordered) // 2]) / 2
            spreads[arm] = ordered[-1] - ordered[0]
            if len(rows) < 4:
                band = f'**incomplete: {len(rows)} of 4 seeds**'
            elif any(row['status'] != 'pass' or a > DEVICE_ALMS for row, a in zip(rows, alms)):
                band = '**band 1: does not fit**'
            elif any(row['timing_status'] != 'pass' for row in rows):
                band = '**band 3: fits but does not pass timing at 61.44 MHz**'
            elif any(a >= BAND4_ALMS for a in alms):
                band = f'**band 4: not established** (a seed at or above {BAND4_ALMS:,} ALMs, 92% of the device)'
            else:
                band = '**band 2: fits and passes timing at 61.44 MHz** on all four seeds'
            out += ['', f'{band}. ALMs needed {ordered[0]:,} to {ordered[-1]:,}, median {medians[arm]:,.1f}, '
                    f'spread {spreads[arm]:,}; the worst seed is {100 * ordered[-1] / DEVICE_ALMS:.2f}% of the device.']
        out.append('')
    if len(medians) == 2:
        delta = medians['trans'] - medians['base']
        floor = max(spreads.values())
        out += ['## The delta', '',
                f'**Controlled** (same seeds, harness and host; only this work differs): the difference of medians is '
                f'**{delta:+,.1f} ALMs**. The test fixed in method.md is the larger of the two arms\' spreads, '
                f'{floor:,} ALMs: the difference is **{"measurable" if abs(delta) > floor else "not measurable"}**.', '']
    prior = []
    for seed in (1, 2, 3, 4):
        file = HERE.parent / '2026-11-16-de25-x87-envelope' / 'integration-fit' / f'fit-seed{seed}.json'
        if file.is_file():
            prior.append(int(json.loads(file.read_text())['resources']['alms']['used']))
    if len(prior) == 4 and 'trans' in medians:
        ordered = sorted(prior)
        median = (ordered[1] + ordered[2]) / 2
        out += [f'**Uncontrolled**, against PR #1907\'s four seeds ({", ".join(f"{a:,}" for a in prior)} ALMs, median '
                f'{median:,.1f}, spread {ordered[-1] - ordered[0]:,}): **{medians["trans"] - median:+,.1f} ALMs** '
                'between medians. Those fits predate #1907\'s own merge of main and main has moved since, so the base '
                'varies as well as the 387; it is given because the brief asks for it and is not evidence of this '
                'work\'s cost.', '']
    return '\n'.join(out) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='fail if a committed generated file is stale')
    args = parser.parse_args()
    generated = {HERE / 'demand.md': demand(), HERE / 'references.md': references(),
                 HERE / 'results.md': results(), HERE / 'lockstep.md': lockstep(), HERE / 'fits.md': fits()}
    stale = []
    for path, text in generated.items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(path.name)
        else:
            path.write_text(text)
    if stale:
        print('stale generated files: ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
