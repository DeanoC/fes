"""Generate this record's tables from committed artifacts.

Nothing here is typed from a run's output: each table is read out of a
committed file, so a figure in the record cannot drift from what produced it.

    python3 docs/validation/2026-11-17-de25-x87-transcendentals/generate.py

writes `demand.md` beside this file from the game census's committed rows
(docs/validation/2026-11-15-i386-x87-game-census/census.jsonl) and
`references.md` from the reports under evidence/. `--check`
fails if the committed copy differs from what would be generated.
"""
from __future__ import annotations

